# Variation generators: produce many phrasings of the same concept
INTRO_PHRASES = [
    "คุณ", "คุณคิดว่า", "บอกฉันเกี่ยวกับ", "เล่าเกี่ยวกับ",
    "ฉันอยากรู้ว่า", "ช่วยอธิบาย", "คุณเคย", "คุณชอบ"
]

FOLLOWUP_PHRASES = [
    "บ้างไหม", "หรือไม่", "ได้หรือไม่", "ไหมครับ", "บ้างครับ",
    "เกี่ยวกับอะไร", "อย่างไร", "เพราะอะไร", "เมื่อไหร่", "ที่ไหน"
]

def generate_variations(q, a, domain, n=50):
    """Generate n variations of a Q&A pair."""
    variations = []
    for i in range(n):
        # Vary the question slightly
        q_var = q
        if i % 5 == 0 and q.startswith("คุณ"):
            q_var = "บอกฉันเกี่ยวกับ" + q[2:] if len(q) > 2 else q
        elif i % 5 == 1:
            q_var = q + " บ้างไหม"
        elif i % 5 == 2:
            q_var = q.replace("คุณ", "ผม", 1) if "คุณ" in q else q
        elif i % 5 == 3:
            q_var = "ฉันอยากรู้ว่า " + q[0].lower() + q[1:] if q else q
        elif i % 5 == 4:
            q_var = q + " ช่วยอธิบายหน่อยได้ไหม"
        
        # Vary the answer slightly  
        a_var = a
        if i % 4 == 0:
            a_var = "ครับ " + a
        elif i % 4 == 1:
            a_var = a + " ครับ"
        elif i % 4 == 2:
            a_var = "ฉันคิดว่า " + a.lower() if a else a
        elif i % 4 == 3:
            a_var = "โดยปกติแล้ว " + a
        
        variations.append({"question": q_var, "answer": a_var, "domain": domain})
    return variations

